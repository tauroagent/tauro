// Writes contracts/test/Golden.sol from the TypeScript seal package, so the Solidity tests
// check the exact leaves, roots and proofs the worker and the verify CLI produce.
// CI reruns this and fails if the file changes.
import { writeFileSync } from "node:fs";
import { buildTree, getProof, leafHash, LeafKind, type LeafInput } from "../packages/seal/src/index.js";

const HOUR = 1_763_215_200;
const inputs: LeafInput[] = Array.from({ length: 7 }, (_, i) => ({
  kind: i === 6 ? LeafKind.Status : LeafKind.Decision,
  subject: i === 6 ? "status.json" : `agent-${i}`,
  hour: HOUR,
  record: i === 6 ? { sha256: "0".repeat(64) } : { agent: `agent-${i}`, action: ["buy", "sell", "hold"][i % 3], price: 100 + i * 0.25 },
}));
const leaves = inputs.map(leafHash);
const tree = buildTree(leaves);

const arr = (xs: string[]) => (xs.length === 0 ? "new bytes32[](0)" : `_a(${xs.length}, [${xs.map((x) => `bytes32(${x})`).join(", ")}])`);
const lines = leaves.map((l, i) => `        out[${i}] = Vector(bytes32(${l}), ${arr(getProof(tree, l))});`);
const maxLen = Math.max(...leaves.map((l) => getProof(tree, l).length), 1);

const src = `// SPDX-License-Identifier: MIT
// Generated by tools/gen-golden.ts. Do not edit by hand.
pragma solidity 0.8.28;

library Golden {
    struct Vector {
        bytes32 leaf;
        bytes32[] proof;
    }

    uint64 internal constant HOUR = ${HOUR};
    bytes32 internal constant ROOT = bytes32(${tree.root});
    uint32 internal constant LEAF_COUNT = ${leaves.length};

    function _a(uint256 n, bytes32[${maxLen}] memory xs) private pure returns (bytes32[] memory out) {
        out = new bytes32[](n);
        for (uint256 i = 0; i < n; i++) out[i] = xs[i];
    }

    function vectors() internal pure returns (Vector[] memory out) {
        out = new Vector[](${leaves.length});
${lines.join("\n")}
    }
}
`;
// Pad shorter proofs to the fixed array size the helper expects.
const fixed = src.replace(/_a\((\d+), \[([^\]]*)\]\)/g, (_m, n: string, body: string) => {
  const items = body.split(", ");
  while (items.length < maxLen) items.push("bytes32(0)");
  return `_a(${n}, [${items.join(", ")}])`;
});
writeFileSync(new URL("../contracts/test/Golden.sol", import.meta.url), fixed);
console.log(`root ${tree.root}, ${leaves.length} leaves`);
